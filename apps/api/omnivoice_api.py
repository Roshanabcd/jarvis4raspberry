"""
JARVIS OS — Google Colab OmniVoice Integration API.
Provides endpoints for:
- POST /api/integrations/omnivoice/register (dynamic Gradio URL registration with token auth)
- GET  /api/integrations/omnivoice/status   (live connectivity, session, and endpoint status)
- POST /api/integrations/omnivoice/verify   (pre-flight verification of Gradio instance)
- POST /api/integrations/omnivoice/test     (synthesize test phrase in cloned voice & speak)
- POST /api/integrations/omnivoice/disconnect (mark integration offline)
"""

import logging
from typing import Optional
from fastapi import APIRouter, HTTPException, Request
from pydantic import BaseModel

from apps.voice.colab_registration import colab_manager

logger = logging.getLogger("JARVIS.API.OmniVoice")
omnivoice_router = APIRouter(prefix="/integrations/omnivoice", tags=["omnivoice"])


class RegisterUrlRequest(BaseModel):
    gradio_url: str
    session_id: Optional[str] = None
    token: Optional[str] = None
    verify: Optional[bool] = True


class VerifyUrlRequest(BaseModel):
    gradio_url: Optional[str] = None


class TestVoiceRequest(BaseModel):
    text: Optional[str] = "Google Colab OmniVoice connection verified. My personal voice model is active."
    play_speaker: Optional[bool] = True


@omnivoice_router.post("/register")
def register_gradio_url(req: RegisterUrlRequest, request: Request):
    """
    Register a dynamic Gradio URL generated by Google Colab or external GPU runtime.
    Validates token, tests HTTPS connectivity and endpoint schema, and updates JARVIS voice pipeline.
    """
    client_ip = request.client.host if request.client else "unknown"
    is_local = client_ip in ("127.0.0.1", "localhost", "::1", "testclient")

    result = colab_manager.register_url(
        gradio_url=req.gradio_url,
        session_id=req.session_id,
        token=req.token,
        is_local_request=is_local,
        client_ip=client_ip,
        verify_now=bool(req.verify),
    )

    if result.get("status") == "error":
        code = result.get("code", 400)
        raise HTTPException(status_code=code, detail=result.get("message", "Registration failed"))

    return result


@omnivoice_router.get("/status")
def get_omnivoice_status():
    """Return live status of the Google Colab OmniVoice integration."""
    return colab_manager.get_status()


@omnivoice_router.post("/verify")
def verify_omnivoice_connection(req: Optional[VerifyUrlRequest] = None):
    """Perform pre-flight verification against a specified or current active Gradio URL."""
    url = (req.gradio_url if req and req.gradio_url else "").strip() or colab_manager.get_active_url()
    if not url:
        raise HTTPException(status_code=400, detail="No Gradio URL specified or active")

    ok, msg, endpoints = colab_manager.verify_remote_gradio(url)
    return {
        "status": "ok" if ok else "error",
        "gradio_url": url,
        "verified": ok,
        "message": msg,
        "endpoints": endpoints,
    }


@omnivoice_router.post("/test")
def test_cloned_voice(req: TestVoiceRequest = TestVoiceRequest()):
    """Synthesize test phrase using OmniVoice cloned voice and optionally speak through physical speaker."""
    from apps.voice.speech_manager import speech_manager

    text = (req.text or "Google Colab OmniVoice connection verified. My personal voice model is active.").strip()
    result = speech_manager.synthesize_and_stage(text, play_system=req.play_speaker)

    return {
        "status": "ok" if result.get("success") else "error",
        "synthesis": result,
        "is_cloned": result.get("is_cloned", False),
        "provider": result.get("provider", "unknown"),
        "audio_url": result.get("audio_url"),
        "message": "Speech synthesized and staged successfully." if result.get("success") else result.get("error"),
    }


@omnivoice_router.post("/disconnect")
def disconnect_omnivoice():
    """Manually mark OmniVoice integration as offline and switch to local/neural fallback."""
    colab_manager.mark_offline("User requested disconnect")
    return {"status": "ok", "message": "OmniVoice marked offline. Neural fallback active."}
