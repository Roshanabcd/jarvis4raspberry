"""
JARVIS OS — Google Colab OmniVoice Dynamic Registration & Connection Manager.

Manages dynamic Gradio share URLs generated by Google Colab runtimes.
Provides:
- Secure registration endpoint authentication
- Real-time HTTPS URL validation and pre-flight health checks
- Atomic voice provider handover without restarting JARVIS
- State persistence in data/omnivoice_state.json
- Lightweight background connection monitoring with backoff
- Graceful offline fallback to Neural TTS when Colab runtime terminates
"""

import json
import logging
import os
import re
import secrets
import threading
import time
import urllib.parse
from typing import Any, Dict, List, Optional, Tuple

import requests
from config.config_manager import config

logger = logging.getLogger("JARVIS.Voice.ColabRegistration")

# Remote registration is disabled until the operator explicitly configures a
# token.  Never ship a reusable registration secret in source code.
DEFAULT_REGISTRATION_TOKEN = ""


class ColabRegistrationManager:
    """Manages dynamic Gradio URL registration, verification, persistence, and health monitoring."""

    def __init__(self, state_file: Optional[str] = None, monitor_enabled: Optional[bool] = None):
        self.project_root = os.path.dirname(os.path.dirname(os.path.dirname(__file__)))
        self.state_file = state_file or os.path.join(self.project_root, "data", "omnivoice_state.json")
        os.makedirs(os.path.dirname(self.state_file), exist_ok=True)

        self._lock = threading.RLock()
        self._monitor_thread: Optional[threading.Thread] = None
        self._stop_monitor = threading.Event()

        v_cfg = config.get("voice", {}) if hasattr(config, "get") else {}
        self.monitor_enabled = (
            bool(v_cfg.get("omnivoice_monitor_enabled", False))
            if monitor_enabled is None
            else bool(monitor_enabled)
        )

        # Load token from config or env
        self.registration_token = (
            os.environ.get("OMNIVOICE_REGISTRATION_TOKEN")
            or v_cfg.get("registration_token")
            or DEFAULT_REGISTRATION_TOKEN
        ).strip()

        # In-memory state with persistence backing
        self.state: Dict[str, Any] = {
            "service": "omnivoice",
            "active_url": "",
            "session_id": "",
            "runtime_status": "not_configured",
            "registered_at": 0.0,
            "last_health_check": 0.0,
            "last_generation_time": 0.0,
            "last_error": None,
            "verified": False,
            "endpoints": [],
            "history": [],
        }

        self._load_state()
        # A persisted endpoint is only monitored when the operator explicitly
        # opted in.  Importing this module must not create network traffic.
        if self.monitor_enabled and self.state.get("verified"):
            self.start_background_monitor()

    def _load_state(self) -> None:
        """Load persisted state from disk if present."""
        with self._lock:
            if os.path.exists(self.state_file):
                try:
                    with open(self.state_file, "r", encoding="utf-8") as f:
                        saved = json.load(f)
                    if isinstance(saved, dict):
                        self.state.update(saved)
                        logger.info("Loaded OmniVoice state: active_url=%s, status=%s",
                                    self.state.get("active_url"), self.state.get("runtime_status"))
                except Exception as e:
                    logger.warning("Failed to load omnivoice_state.json: %s", e)

            # A configured URL is informational until the operator explicitly
            # registers/verifies it.  Do not seed a public fallback URL.
            if not self.state.get("active_url"):
                default_url = (
                    os.environ.get("GRADIO_VOICE_URL")
                    or (config.get("voice", {}).get("gradio_url") if hasattr(config, "get") else None)
                )
                if default_url and default_url.startswith("http"):
                    self.state["active_url"] = default_url.strip()
                    self.state["runtime_status"] = "configured_unverified"

            # Older state files may have marked an endpoint ready without the
            # explicit verification marker introduced by this manager.  Treat
            # those URLs as informational until they are registered again.
            if self.state.get("active_url") and not self.state.get("verified", False):
                self.state["runtime_status"] = "configured_unverified"

    def _save_state(self) -> None:
        """Persist state to disk safely with atomic write."""
        with self._lock:
            try:
                tmp_path = self.state_file + ".tmp"
                with open(tmp_path, "w", encoding="utf-8") as f:
                    json.dump(self.state, f, indent=2)
                os.replace(tmp_path, self.state_file)
            except Exception as e:
                logger.error("Failed to save omnivoice_state.json: %s", e)

    def validate_url(self, url: str) -> Tuple[bool, str]:
        """
        Validate URL format and security:
        - Must begin with https:// (or http:// for local debug tunnels)
        - Must not be local/private loopback when registering external Colab instance
        - Must have a valid hostname (e.g. *.gradio.live, *.hf.space, *.ngrok.io, *.trycloudflare.com)
        """
        if not url or not isinstance(url, str):
            return False, "URL cannot be empty"

        url = url.strip()
        parsed = urllib.parse.urlparse(url)

        if parsed.scheme not in ("http", "https"):
            return False, f"Invalid URL scheme '{parsed.scheme}'. Must be https://"

        if not parsed.netloc:
            return False, "URL must contain a valid domain host"

        host = parsed.netloc.split(":")[0].lower()

        # Reject private/loopback IPs when registering remote Colab service
        private_patterns = [
            r"^localhost$",
            r"^127\.\d+\.\d+\.\d+$",
            r"^0\.0\.0\.0$",
            r"^10\.\d+\.\d+\.\d+$",
            r"^192\.168\.\d+\.\d+$",
            r"^172\.(1[6-9]|2\d|3[01])\.\d+\.\d+$",
            r"^::1$",
        ]
        for pat in private_patterns:
            if re.match(pat, host):
                return False, f"Host '{host}' is a private/loopback address. Colab URLs must be public."

        return True, ""

    def verify_remote_gradio(self, url: str, timeout: float = 6.0) -> Tuple[bool, str, List[str]]:
        """
        Verify that the remote Gradio instance is accessible and exposes the OmniVoice API.
        Returns: (success: bool, message: str, endpoints: List[str])
        """
        url = url.strip()
        try:
            # 1. Fast HTTP pre-flight check
            resp = requests.head(url, timeout=timeout, allow_redirects=True)
            if resp.status_code == 405:
                resp = requests.get(url, timeout=timeout)
            if resp.status_code >= 400:
                return False, f"Server returned HTTP {resp.status_code} ({resp.reason})", []
        except requests.exceptions.Timeout:
            return False, f"Connection timed out after {timeout}s", []
        except requests.exceptions.RequestException as e:
            return False, f"Network error connecting to {url}: {e}", []

        # 2. Inspect Gradio API schema via gradio_client
        try:
            from gradio_client import Client
            client = Client(url)
            api_info = client.view_api(return_format="dict")
            named = list(api_info.get("named_endpoints", {}).keys()) if api_info else []

            # Verify that speech generation endpoint exists
            has_gen = any("/generate" in ep or "generate" in ep or "/clone_voice" in ep for ep in named)
            if not has_gen and named:
                logger.warning("Gradio server at %s responded but lacks expected speech endpoints: %s", url, named)

            return True, "Gradio API verified successfully", named
        except Exception as exc:
            # Server responded on HTTP, but API inspection had an issue (e.g. older gradio version)
            logger.warning("Gradio view_api warning for %s: %s (accepting HTTP 200)", url, exc)
            return True, f"HTTP reachable (API warning: {exc})", []

    def register_url(
        self,
        gradio_url: str,
        session_id: Optional[str] = None,
        token: Optional[str] = None,
        is_local_request: bool = False,
        client_ip: Optional[str] = None,
        verify_now: bool = True,
    ) -> Dict[str, Any]:
        """
        Register a new Gradio public URL from Google Colab.
        Performs authentication, validation, connectivity verification, and atomic handover.
        """
        clean_url = gradio_url.strip() if gradio_url else ""

        # 1. Authenticate registration
        if not is_local_request:
            if (
                not self.registration_token
                or not token
                or not secrets.compare_digest(token, self.registration_token)
            ):
                logger.warning("Registration rejected: unauthorized token from IP %s", client_ip)
                return {
                    "status": "error",
                    "code": 401,
                    "message": "Invalid or missing registration token. Registration rejected.",
                    "authenticated": False,
                }

        # 2. Validate URL structure
        valid, err_msg = self.validate_url(clean_url)
        if not valid:
            logger.warning("Registration rejected: %s", err_msg)
            return {
                "status": "error",
                "code": 400,
                "message": err_msg,
                "authenticated": True,
            }

        # 3. Verify server if requested
        endpoints = []
        if verify_now:
            ok, msg, endpoints = self.verify_remote_gradio(clean_url)
            if not ok:
                logger.warning("Registration verification failed for %s: %s", clean_url, msg)
                return {
                    "status": "error",
                    "code": 502,
                    "message": f"Server verification failed: {msg}",
                    "gradio_url": clean_url,
                    "authenticated": True,
                }

        # 4. Atomic handover
        with self._lock:
            prev_url = self.state.get("active_url")
            now = time.time()

            # Record in history (keeping max 10 entries)
            if prev_url and prev_url != clean_url:
                history = self.state.get("history", [])
                history.insert(0, {
                    "url": prev_url,
                    "session_id": self.state.get("session_id"),
                    "retired_at": now,
                })
                self.state["history"] = history[:10]

            self.state["active_url"] = clean_url
            self.state["session_id"] = session_id or f"colab_{int(now)}"
            self.state["runtime_status"] = "ready"
            self.state["registered_at"] = now
            self.state["last_health_check"] = now
            self.state["last_error"] = None
            self.state["verified"] = True
            self.state["endpoints"] = endpoints
            self._save_state()

        if self.monitor_enabled:
            self.start_background_monitor()

        # 5. Notify GradioVoiceCloner
        try:
            from apps.voice.gradio_tts import gradio_cloner
            gradio_cloner.update_url(clean_url, api_info={"named_endpoints": {ep: {} for ep in endpoints}})
            logger.info("Successfully registered & activated OmniVoice URL: %s (session=%s)",
                        clean_url, self.state["session_id"])
        except Exception as e:
            logger.error("Failed to notify gradio_cloner of new URL: %s", e)

        return {
            "status": "ok",
            "message": "OmniVoice Gradio URL registered and verified successfully.",
            "gradio_url": clean_url,
            "session_id": self.state["session_id"],
            "runtime_status": "ready",
            "endpoints": endpoints,
            "registered_at": self.state["registered_at"],
        }

    def get_status(self) -> Dict[str, Any]:
        """Return comprehensive status for UI, diagnostics, and monitoring."""
        with self._lock:
            active_url = self.state.get("active_url", "")
            # Mask token for security in UI output
            tok = self.registration_token
            masked_token = f"{tok[:3]}...{tok[-3:]}" if len(tok) >= 8 else "***"

            return {
                "service": "omnivoice",
                "active_url": active_url,
                "runtime_status": self.state.get("runtime_status", "not_configured"),
                "session_id": self.state.get("session_id", ""),
                "registered_at": self.state.get("registered_at", 0.0),
                "last_health_check": self.state.get("last_health_check", 0.0),
                "last_generation_time": self.state.get("last_generation_time", 0.0),
                "last_error": self.state.get("last_error"),
                "verified": self.state.get("verified", False),
                "endpoints": self.state.get("endpoints", []),
                "history_count": len(self.state.get("history", [])),
                "registration_token_masked": masked_token,
                "cloned_voice_ready": self.state.get("runtime_status") == "ready",
                "monitor_enabled": self.monitor_enabled,
                "monitor_running": bool(self._monitor_thread and self._monitor_thread.is_alive()),
            }

    def get_active_url(self) -> str:
        """Return the configured URL for operator-facing status displays."""
        with self._lock:
            return self.state.get("active_url", "")

    def get_verified_active_url(self) -> str:
        """Return a registered endpoint only when it is currently verified.

        Code that could cause outbound traffic must use this method rather than
        treating a configuration value as an approved external destination.
        """
        with self._lock:
            if (
                self.state.get("verified", False)
                and self.state.get("runtime_status") == "ready"
            ):
                return self.state.get("active_url", "")
            return ""

    def mark_offline(self, reason: str = "Server unreachable") -> None:
        """Mark integration as offline and notify gradio_cloner to use fallback."""
        with self._lock:
            self.state["runtime_status"] = "offline"
            self.state["last_error"] = reason
            self._save_state()

        try:
            from apps.voice.gradio_tts import gradio_cloner
            gradio_cloner._online = False
        except Exception:
            pass

    def start_background_monitor(self) -> None:
        """Start daemon thread for periodic lightweight connection checks.

        Callers must opt in through ``monitor_enabled``.  This method is kept
        explicit so a module import or failed provider never creates a retry
        loop against a remote host.
        """
        if not self.monitor_enabled:
            logger.info("OmniVoice health monitor remains disabled by configuration.")
            return
        if self._monitor_thread and self._monitor_thread.is_alive():
            return

        self._stop_monitor.clear()
        self._monitor_thread = threading.Thread(
            target=self._monitor_loop,
            daemon=True,
            name="OmniVoice-HealthMonitor"
        )
        self._monitor_thread.start()
        logger.info("OmniVoice background health monitor started.")

    def stop_background_monitor(self) -> None:
        """Stop the optional monitor promptly, including in tests and shutdown."""
        self._stop_monitor.set()
        thread = self._monitor_thread
        if thread and thread.is_alive() and thread is not threading.current_thread():
            thread.join(timeout=1.0)
        self._monitor_thread = None

    def _monitor_loop(self) -> None:
        """Lightweight monitor loop: checks active URL every 45s."""
        while not self._stop_monitor.wait(45.0):
            if not self.monitor_enabled:
                break

            active_url = self.get_active_url()
            if not active_url or not active_url.startswith("http"):
                continue

            try:
                # Fast HEAD check (3s timeout) — NEVER expensive generation
                resp = requests.head(active_url, timeout=3.0, allow_redirects=True)
                if resp.status_code == 405:
                    resp = requests.get(active_url, timeout=3.0)

                with self._lock:
                    if resp.status_code < 400:
                        self.state["runtime_status"] = "ready"
                        self.state["last_health_check"] = time.time()
                        self.state["last_error"] = None
                    else:
                        # 404 / 502 means Colab session has terminated
                        logger.info("OmniVoice server at %s returned %d. Marking offline.", active_url, resp.status_code)
                        self.state["runtime_status"] = "offline"
                        self.state["last_error"] = f"HTTP {resp.status_code}"
                        from apps.voice.gradio_tts import gradio_cloner
                        gradio_cloner._online = False
                    self._save_state()
            except Exception as exc:
                with self._lock:
                    logger.debug("OmniVoice health probe error: %s", exc)
                    self.state["runtime_status"] = "offline"
                    self.state["last_error"] = str(exc)
                    self._save_state()
                try:
                    from apps.voice.gradio_tts import gradio_cloner
                    gradio_cloner._online = False
                except Exception:
                    pass


# Global singleton instance
colab_manager = ColabRegistrationManager()
__all__ = ["ColabRegistrationManager", "colab_manager", "DEFAULT_REGISTRATION_TOKEN"]
